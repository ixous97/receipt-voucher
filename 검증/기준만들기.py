"""브라우저 판(docx생성.js)이 파이썬 판(문서생성.py)과 같은 문서를 내는지 대조하기 위한 기준.

시험용 이미지는 일부러 단색으로 만든다. 배치 계산에 쓰이는 것은 가로세로 비율뿐이고,
그림 내용은 결과 XML에 영향을 주지 않는다. 대신 파일이 작아 브라우저에서 결과를
통째로 회수해 비교하기 쉬워진다.
"""
import sys
from pathlib import Path

여기 = Path(__file__).resolve().parent
sys.path.insert(0, str(여기.parent / "src" / "core"))

from PIL import Image                       # noqa: E402

import 문서생성                              # noqa: E402
from 모델 import 결의서, 섹션, 영수증          # noqa: E402

# 실제 영수증에서 흔한 두 가지 모양 — 세로로 긴 감열지, 정사각에 가까운 앱 캡처
크기들 = [(480, 900), (480, 900), (480, 900), (480, 900), (700, 760), (700, 760)]
색들 = ["#e8e8e8", "#d0d0d0", "#b8b8b8", "#a0a0a0", "#888888", "#707070"]

그림방 = 여기 / "그림"
그림방.mkdir(exist_ok=True)

경로들 = []
for i, ((w, h), 색) in enumerate(zip(크기들, 색들), 1):
    p = 그림방 / f"시험{i}.jpg"
    Image.new("RGB", (w, h), 색).save(p, "JPEG", quality=85)
    경로들.append(p)

# 가장 까다로운 배치를 고른다 — 왼쪽 4장(두 줄로 쪼개짐) + 오른쪽 2장(한 줄)
왼 = 섹션(설명="스텝 식대")
for p in 경로들[:4]:
    왼.영수증들.append(영수증(경로=p, 금액=12_000, 날짜="0813", 확인필요=False))
오 = 섹션(설명="스튜디오 대여")
for p in 경로들[4:]:
    오.영수증들.append(영수증(경로=p, 금액=90_000, 날짜="0827", 확인필요=False))

결 = 결의서(날짜="2026년 9월 4일", 지출인="홍길동", 항목들=[왼, 오])
나온것 = 문서생성.만들기([결], 여기 / "기준.docx")

print(f"기준 문서: {나온것}  ({나온것.stat().st_size / 1024:.0f} KB)")
print(f"총금액 {결.총금액:,}원 / {결.매수}매")
print(f"왼쪽 {왼.매수}장 → {왼.가로칸수()}줄 × {왼.세로칸수()}칸, 설명 '{왼.설명완성()}'")
print(f"오른쪽 {오.매수}장 → {오.가로칸수()}줄 × {오.세로칸수()}칸, 설명 '{오.설명완성()}'")
