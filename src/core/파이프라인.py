"""영수증 폴더 → 판독 → 좌/우 섹션 → 워드 문서까지 한 번에 잇는다."""
from pathlib import Path

from 모델 import 섹션, 영수증, 최대섹션수, 페이지나누기
import 문서생성
import 영수증판독 as 판독기
from 이미지정리 import 정규화


def 읽어오기(영수증폴더: Path, 작업폴더: Path, 진행=None) -> list:
    """폴더를 훑어 왼쪽·오른쪽 두 섹션으로 나누고 각 영수증을 판독한다.

    나누는 규칙
      · 하위 폴더는 각각 하나의 섹션이 된다 (최대 2개)
      · 낱장 파일은 모두 모아 남은 섹션에 넣는다
      · 그래도 넘치면 마지막 섹션에 합친다. 화면에서 '쪽' 번호로 옮기면 된다
    """
    묶음들 = 판독기.폴더읽기(영수증폴더)
    폴더묶음 = [m for m in 묶음들 if m["출처"] == "폴더"]
    낱장파일 = [f for m in 묶음들 if m["출처"] == "낱장" for f in m["파일들"]]

    할일 = [(m["설명"], m["파일들"]) for m in 폴더묶음]
    if 낱장파일:
        이름 = 낱장파일[0].stem if len(낱장파일) == 1 else ""
        할일.append((이름, 낱장파일))

    전체 = sum(len(파일들) for _, 파일들 in 할일)
    센것 = 0
    섹션들 = []

    for 설명, 파일들 in 할일:
        영수증들 = []
        for f in 파일들:
            센것 += 1
            if 진행:
                진행(센것, 전체, f.name)
            읽음 = 판독기.판독(f, 작업폴더)
            영수증들.append(영수증(
                경로=f, 금액=읽음["금액"], 날짜=읽음["날짜"],
                확인필요=읽음["확인필요"], 후보=읽음["후보"], 근거=읽음["근거"],
            ))
        if len(섹션들) < 최대섹션수:
            # 설명은 폴더명·파일명만 담아 두고, 날짜와 건수는 설명완성()이 그때그때 붙인다.
            # 그래야 영수증을 옮길 때마다 문구가 자동으로 따라 바뀐다.
            섹션들.append(섹션(설명=설명, 영수증들=영수증들))
        elif 섹션들:
            섹션들[-1].영수증들.extend(영수증들)

    return 섹션들


def 문서만들기(결의서들: list, 저장경로: Path, 작업폴더: Path) -> Path:
    """워드 문서를 만든다.

    영수증이 한 장에 다 안 들어가면 같은 양식으로 다음 페이지를 이어 만든다.
    넣기 전에 이미지를 가볍게 정규화해 파일이 무거워지지 않게 한다.
    """
    쪽들 = []
    for 결 in 결의서들:
        쪽들.extend(페이지나누기(결))

    for 쪽 in 쪽들:
        for r in 쪽.영수증들:
            if r.경로.suffix.lower() != ".pdf":
                r.경로 = 정규화(r.경로, 작업폴더 / "삽입용")
    return 문서생성.만들기(쪽들, 저장경로)
