"""사용설명서를 워드 문서로 만든다. 받는 사람이 더블클릭만 하면 열리도록."""
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor


def _고정폭(문단, 글):
    실행 = 문단.add_run(글)
    실행.font.name = "D2Coding"
    실행.font.size = Pt(9)
    return 실행


def 만들기(저장경로: Path) -> Path:
    doc = Document()
    기본 = doc.styles["Normal"]
    기본.font.name = "맑은 고딕"
    기본.font.size = Pt(10.5)

    제목 = doc.add_heading("지출결의서 증빙 만들기 — 사용설명서", level=0)
    제목.alignment = WD_ALIGN_PARAGRAPH.CENTER

    앞말 = doc.add_paragraph()
    앞말.add_run("영수증 사진을 넣으면 금액을 자동으로 읽어 지출결의서 증빙 워드 문서를 만들어 줍니다. "
               "합계와 영수증 매수는 프로그램이 계산하므로 따로 더할 필요가 없습니다.")
    for 줄 in ("인터넷이 없어도 됩니다.",
              "따로 설치하거나 로그인할 것이 없습니다.",
              "비용이 들지 않습니다."):
        doc.add_paragraph(줄, style="List Bullet")

    # ── 문서 모양 ────────────────────────────────────────────────
    doc.add_heading("문서가 만들어지는 모양", level=1)
    doc.add_paragraph("문서 한 장은 왼쪽 쪽과 오른쪽 쪽 두 덩어리로 나뉩니다.")
    그림 = doc.add_paragraph()
    _고정폭(그림,
         "┌────────────────────┬────────────────────┐\n"
         "│  0813,20 스텝 식대  │  0829 스튜디오 대여  │\n"
         "│      454,500원      │      180,000원      │\n"
         "│                    │                    │\n"
         "│  [영수증] [영수증]   │      [영수증]        │\n"
         "│  [영수증] [영수증]   │                    │\n"
         "│  [영수증]           │                    │\n"
         "└────────────────────┴────────────────────┘\n"
         "      ← 1쪽(왼쪽) →         ← 2쪽(오른쪽) →")
    for 줄 in ("왼쪽과 오른쪽은 폭이 정확히 반반이고, 가운데 굵은 세로선으로 나뉩니다.",
              "쪽마다 설명 문구 하나와, 그 쪽 영수증들의 합계가 붙습니다.",
              "한 쪽에는 영수증 6장까지 들어갑니다. 더 넣으려 하면 막고 알려 드립니다.",
              "영수증 크기는 장수에 맞춰 자동으로 조절됩니다 (1~3장은 크게, 4~6장은 두 줄로)."):
        doc.add_paragraph(줄, style="List Bullet")

    doc.add_heading("쪽 번호", level=2)
    doc.add_paragraph("각 자리에는 번호가 붙어 있습니다. 두 쪽이 모여 문서 한 장이 됩니다.")
    쪽표 = doc.add_table(rows=1, cols=2)
    쪽표.style = "Light Grid Accent 1"
    머리 = 쪽표.rows[0].cells
    머리[0].text, 머리[1].text = "쪽 번호", "자리"
    for 번호, 자리 in [("1쪽 / 2쪽", "문서 1장의 왼쪽 / 오른쪽"),
                    ("3쪽 / 4쪽", "문서 2장의 왼쪽 / 오른쪽"),
                    ("5쪽 / 6쪽", "문서 3장의 왼쪽 / 오른쪽"),
                    ("… 10쪽까지", "… 문서 5장까지")]:
        칸 = 쪽표.add_row().cells
        칸[0].text, 칸[1].text = 번호, 자리
    doc.add_paragraph(
        "영수증이 많으면 3쪽, 4쪽… 으로 옮겨 담으면 문서가 저절로 여러 장이 됩니다.")

    # ── 준비 ────────────────────────────────────────────────────
    doc.add_heading("1. 준비 — 영수증 모으기", level=1)
    doc.add_paragraph("빈 폴더를 만들고 영수증 사진을 넣습니다.")
    예시 = doc.add_paragraph()
    _고정폭(예시,
         "9월 영수증\\\n"
         "├─ 스튜디오 대여.jpg      ← 낱장들은 모두 한 섹션으로 묶입니다\n"
         "├─ 택시비.jpg\n"
         "└─ 스텝 식대\\            ← 폴더 하나가 섹션 하나가 됩니다\n"
         "     ├─ 0813.jpg\n"
         "     ├─ 0820.jpg\n"
         "     └─ 0827.jpg")
    for 줄 in ("폴더를 만들면 그 폴더가 하나의 쪽이 됩니다 (1쪽부터 차례로).",
              "낱장 파일들은 모두 모여 한 쪽이 됩니다.",
              "폴더 이름과 파일 이름이 설명 문구의 바탕이 됩니다. 알아보기 쉽게 지어 주세요.",
              "날짜와 건수는 영수증에서 읽어 자동으로 붙습니다.",
              "넣을 수 있는 형식: 스마트폰 사진(JPG·PNG·아이폰 HEIC), 스캔 이미지, PDF 영수증"):
        doc.add_paragraph(줄, style="List Bullet")

    # ── 사용 순서 ────────────────────────────────────────────────
    doc.add_heading("2. 사용 순서", level=1)
    순서 = [
        ("① 프로그램 실행", "「지출결의서 증빙 만들기.exe」를 두 번 누릅니다. 처음 뜰 때 5~10초쯤 걸립니다."),
        ("② 영수증 폴더 열기", "왼쪽 위 [영수증 폴더 열기]를 눌러 1번에서 만든 폴더를 고릅니다."),
        ("③ 부서명·날짜·지출인 입력", "부서명과 날짜는 미리 채워져 있습니다. 지출인에 본인 이름을 넣으세요."),
        ("④ 영수증 읽기", "[영수증 읽기]를 누릅니다. 한 장에 1초쯤 걸립니다."),
        ("⑤ 금액 확인하기", "가장 중요한 단계입니다. 아래 표를 참고하세요."),
        ("⑥ 다른 쪽으로 옮기기", "어느 자리에 넣을지 정합니다. 아래 설명을 참고하세요."),
        ("⑦ 워드 문서 만들기", "[워드 문서 만들기]를 누르고 저장 위치를 고르면 끝입니다."),
    ]
    for 이름, 설명 in 순서:
        p = doc.add_paragraph()
        p.add_run(이름 + "  ").bold = True
        p.add_run(설명)

    붙 = doc.add_paragraph()
    붙.add_run("캡처한 이미지를 바로 붙여넣을 수도 있습니다.  ").bold = True
    붙.add_run("카드사 앱이나 화면을 캡처해 복사한 뒤 Ctrl + V 를 누르면 그대로 영수증으로 "
             "들어갑니다(캡처 단축키: 윈도우 키 + Shift + S). 파일로 저장할 필요가 없어 "
             "카드 이용내역을 넣을 때 가장 빠릅니다. 폴더를 열지 않고 붙여넣기만 해도 됩니다.")

    doc.add_heading("⑤ 금액 확인하는 방법", level=2)
    doc.add_paragraph("표에서 영수증을 누르면 왼쪽에 원본이 크게 보입니다. 실제 금액과 대조하세요.")
    표 = doc.add_table(rows=1, cols=2)
    표.style = "Light Grid Accent 1"
    머리 = 표.rows[0].cells
    머리[0].text, 머리[1].text = "상황", "할 일"
    for 상황, 할일 in [
        ("금액이 맞다", "'확인' 칸을 한 번 누릅니다 → 확인됨으로 바뀝니다"),
        ("금액이 틀렸다", "금액 칸을 두 번 눌러 직접 고칩니다"),
        ("입력이 번거롭다", "금액 칸에서 오른쪽 버튼 → 영수증에서 읽어낸 숫자 중에서 고릅니다"),
    ]:
        칸 = 표.add_row().cells
        칸[0].text, 칸[1].text = 상황, 할일

    경고 = doc.add_paragraph()
    실행 = 경고.add_run("⚠ 표시가 남아 있으면 문서가 만들어지지 않습니다. "
                     "회계 문서이므로 모든 금액을 사람이 확인하도록 되어 있습니다.")
    실행.bold = True
    실행.font.color.rgb = RGBColor(0xA1, 0x5C, 0x00)

    doc.add_heading("⑥ 영수증을 다른 쪽으로 옮기기", level=2)
    doc.add_paragraph("어느 영수증을 어느 자리에 넣을지 바꾸는 방법은 세 가지입니다.")
    for 줄 in ("'쪽' 칸에 번호 넣기 — 두 번 눌러 1~10 중 하나를 입력합니다. 가장 빠릅니다.",
              "버튼 사용 — 영수증을 고르고 [◀ 앞쪽으로] 또는 [뒤쪽으로 ▶]. "
              "Ctrl 키를 누른 채 고르면 여러 장을 한 번에 옮길 수 있습니다.",
              "오른쪽 버튼을 누르면 '3쪽(2장 왼쪽)으로 옮기기'처럼 가까운 쪽이 나옵니다."):
        doc.add_paragraph(줄, style="List Number")
    꽉 = doc.add_paragraph()
    꽉.add_run("한 쪽이 6장으로 차면 더 넣을 수 없습니다. ").bold = True
    꽉.add_run("이때는 '1장 왼쪽(1쪽)이 이미 6장으로 꽉 찼습니다'라고 알려 드립니다. "
             "[뒤쪽으로 ▶]를 눌러 다음 쪽으로 넘기면 문서가 한 장 늘어납니다.")
    doc.add_paragraph(
        "설명 문구도 두 번 눌러 고칠 수 있습니다. 손대지 않으면 날짜와 건수가 자동으로 따라 바뀝니다.")

    doc.add_heading("⑦ 만든 뒤 바로 확인하기", level=2)
    doc.add_paragraph(
        "문서를 다 만들면 \"지금 열어서 확인해 보시겠습니까?\" 라고 물어봅니다. "
        "'예'를 누르면 워드가 바로 열려 결과를 확인할 수 있습니다.")

    # ── 정확도 ──────────────────────────────────────────────────
    doc.add_heading("3. 자동 판독은 얼마나 정확한가요?", level=1)
    doc.add_paragraph("실제 영수증 12장으로 시험한 결과입니다.")
    표2 = doc.add_table(rows=1, cols=2)
    표2.style = "Light Grid Accent 1"
    머리 = 표2.rows[0].cells
    머리[0].text, 머리[1].text = "영수증 종류", "정확도"
    for 종류, 값 in [("카드사 앱·웹 화면 캡처", "8장 중 8장 (100%)"),
                   ("감열지 영수증을 찍은 사진", "4장 중 3장 (75%)"),
                   ("전체", "12장 중 11장 (92%)")]:
        칸 = 표2.add_row().cells
        칸[0].text, 칸[1].text = 종류, 값
    doc.add_paragraph("틀린 1장도 정답이 후보 목록에 있어, 오른쪽 버튼으로 고르면 바로 해결됐습니다.")

    doc.add_heading("더 잘 읽히게 찍는 요령", level=2)
    for 줄 in ("영수증을 평평하게 펴서 찍으세요. 구겨지면 글자가 뭉개집니다.",
              "밝은 곳에서 그림자가 지지 않게 찍으세요.",
              "영수증이 화면에 꽉 차게 찍으세요.",
              "카드사 앱의 이용내역 화면을 캡처하면 가장 정확합니다."):
        doc.add_paragraph(줄, style="List Bullet")

    # ── FAQ ────────────────────────────────────────────────────
    doc.add_heading("4. 자주 묻는 질문", level=1)
    for 질문, 답 in [
        ("영수증을 몇 장까지 넣을 수 있나요?",
         "한 쪽에 6장, 쪽은 10개까지이므로 최대 60장(문서 5장)입니다. "
         "화면 아래에 '문서 3장'처럼 몇 장이 될지 미리 알려 드립니다."),
        ("'이미 6장으로 꽉 찼습니다'가 떠요.",
         "그 쪽이 가득 찼다는 뜻입니다. [뒤쪽으로 ▶]를 눌러 다음 쪽으로 넘기세요. "
         "3쪽으로 넘기면 문서가 2장이 되고, 5쪽으로 넘기면 3장이 됩니다."),
        ("문서를 만들려는데 '아직 문서를 만들 수 없습니다'가 떠요.",
         "확인하지 않은 금액이 남았거나 지출인·날짜가 비어 있습니다. 안내에 적힌 항목을 채워 주세요."),
        ("붙여넣은 이미지는 어디에 저장되나요?",
         "영수증 폴더 안 '붙여넣은영수증' 폴더에 자동으로 저장됩니다. 폴더를 열지 않고 "
         "붙여넣었다면 임시 폴더에 저장되며 화면 아래에 그 위치가 표시됩니다."),
        ("목록에서 영수증을 빼고 싶어요.",
         "그 영수증에서 오른쪽 버튼을 눌러 '이 영수증 목록에서 빼기'를 고르세요. "
         "파일 자체는 지워지지 않습니다."),
        ("금액을 잘못 확인했어요.", "'확인' 칸을 다시 누르면 경고 상태로 돌아갑니다."),
        ("원본 사진이 바뀌나요?", "바뀌지 않습니다. 폴더 안에 _작업 폴더를 만들어 사본으로 작업합니다."),
        ("인터넷이 필요한가요?", "필요 없습니다. 모든 처리가 내 컴퓨터 안에서 이루어집니다."),
    ]:
        p = doc.add_paragraph()
        p.add_run("Q. " + 질문).bold = True
        doc.add_paragraph("A. " + 답)

    doc.add_heading("5. 꼭 알아두실 점", level=1)
    doc.add_paragraph(
        "금액의 최종 확인은 사람이 합니다. 자동 판독은 입력을 대신 채워 주는 보조 기능이며, "
        "결재 상신 전 금액 확인 책임은 작성자에게 있습니다.")
    doc.add_paragraph(
        "설명 문구의 성격(누구 식대인지 등)은 영수증에 적혀 있지 않아 자동으로 알 수 없습니다. "
        "날짜·금액·건수까지만 자동이고, 나머지는 직접 적어 주세요.")

    저장경로.parent.mkdir(parents=True, exist_ok=True)
    doc.save(저장경로)
    return 저장경로


if __name__ == "__main__":
    print(만들기(Path("배포/사용설명서.docx")))
